import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const contracts=JSON.parse(await fs.readFile('edition-contracts.json','utf8'));
const html=await fs.readFile('index.html','utf8');
const app=await fs.readFile('js/app.js','utf8');
const quiz=await fs.readFile('js/laneway-quiz.js','utf8');
const css=await fs.readFile('styles.css','utf8');
const factory=await fs.readFile('scripts/create-edition.mjs','utf8');
const validator=await fs.readFile('scripts/validate-platform.mjs','utf8');
const artwork=await fs.readFile('scripts/generate-social-assets.py','utf8');
const celibateRifles=JSON.parse(await fs.readFile('editions/celibate-rifles/edition.json','utf8'));

assert.deepEqual(contracts.editionTypes.laneway.brandNames,['Laneway']);
assert.deepEqual(contracts.editionTypes.laneway.exclusiveConfig,['laneway','lanewayChallenge']);
for(const key of ['buyMusic','spotify','instagram','bandcamp','youtube','facebook','website','merchandise','newsReviews'])assert.ok(contracts.editionTypes.laneway.allowedLinks.includes(key));
assert.ok(html.includes('id="editionBrandLogo"'));
assert.ok(html.includes('src="/js/laneway-quiz.js'));
for(const id of ['lanewayHomeLink','shareButton','lanewayRecommendedLink'])assert.ok(html.includes(`id="${id}"`),`Missing Laneway utility control ${id}.`);
assert.ok(html.indexOf('id="featuredVideo"')<html.indexOf('id="platformLinks"'),'Featured video must precede artist destination cards.');
assert.ok(html.indexOf('id="platformLinks"')<html.indexOf('id="editionUtilityActions"'),'Laneway utility navigation must follow artist destinations and challenge.');
assert.match(app,/isLanewayEdition\(\)/);
assert.match(app,/LanewayQuiz\.configure/);
assert.match(app,/createLanewayChallengeCard/);
assert.match(app,/if\(isLanewayEdition\(\)\)els\.links\.append\(createLanewayChallengeCard\(\)\)/);
assert.doesNotMatch(app,/if\(isLanewayEdition\(\)\)els\.links\.append\(createLanewayChallengeCard\(\)\);\s*for\(const definition/);
assert.match(app,/record_company_home/);
assert.match(app,/recommended_artists/);
assert.match(app,/els\.poweredBy\.textContent=laneway\?"Deep Cuts"/);
assert.match(app,/els\.artwork\.removeAttribute\("src"\)/);
assert.match(quiz,/value\.length!==5/);
assert.match(quiz,/prepareQuestions\(questionBank,5\)/);
assert.match(quiz,/question_count:5/);
assert.match(quiz,/Good choice — here is the story\./);
assert.doesNotMatch(quiz,/SchoolDiscoveryQuiz|schoolChallenge|Aggits/);
assert.match(css,/\[data-edition-type="laneway"\] \.edition-brand-logo\{[^}]*filter:invert\(1\)/);
assert.match(css,/\[data-edition-type="laneway"\] \.discovery-shell\{[^}]*#161616/);
assert.match(css,/\[data-edition-type="laneway"\] \.edition-utility-actions\{[^}]*grid-template-columns:repeat\(3/);
assert.match(factory,/editionType===['"]laneway['"]/);
assert.match(factory,/exactly five positive, informative and sourced band questions/);
assert.match(factory,/logoArtwork:'assets\/laneway-music-logo-source\.jpg'/);
assert.match(factory,/heroLabels:\['Listen','Watch','Discover','Buy'\]/);
assert.match(factory,/official-label-feature/);
assert.match(validator,/Laneway must never configure Aggits/);
assert.match(validator,/recordCompanyHomeURL/);
assert.match(validator,/recommendedArtistsURL/);
assert.match(artwork,/elif config\.get\("editionType"\) == "laneway":/);
assert.match(artwork,/create_laneway_instagram/);
assert.match(artwork,/create_laneway_qr/);
const lanewayArtwork=artwork.split('def create_laneway_instagram')[1].split('def create_qr')[0];
assert.doesNotMatch(lanewayArtwork,/aggits/i);
assert.equal((lanewayArtwork.match(/centred_text\(draw, "DEEP CUTS"/g)||[]).length,2,'Both Laneway delivery images must identify Deep Cuts above the copyright notice.');
assert.doesNotMatch(lanewayArtwork,/centred_text\(draw, "LANEWAY"/,'Laneway delivery footers must not repeat the Laneway name above copyright.');
assert.deepEqual(celibateRifles.laneway.heroLabels,['Listen','Watch','Discover','Buy']);
assert.equal(celibateRifles.laneway.recordCompanyHomeURL,'https://www.lanewaymusic.com.au/');
assert.equal(celibateRifles.laneway.recommendedArtistsURL,'https://www.lanewaymusic.com.au/');
assert.equal(celibateRifles.featuredVideo.selectionBasis,'official-label-feature');
assert.match(celibateRifles.featuredVideo.youtubeURL,/^https:\/\/www\.youtube\.com\/watch\?v=[A-Za-z0-9_-]{11}$/);
await fs.access('assets/laneway-music-logo-source.jpg');

console.log('Laneway edition tests passed: official video, destination cards, bottom quiz, Home/Share/Recommended navigation, Deep Cuts footer and isolated five-question positive quiz.');
